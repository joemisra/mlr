#!/usr/bin/env node
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),dest=path.join(root,'firmware/dpt/bank');
const names=['kick','snare','hat','clap','tom','rim','bell','bass'];
const read=f=>JSON.parse(fs.readFileSync(path.join(root,f))).patcher;
const boxes=[],lines=[],manifest=[];
for(const [v,name] of names.entries()){
 const model=require(path.join(root,name==='kick'?'instrument_model':name+'_instrument_model'));
 const params=model[name.toUpperCase()+'_LOCKS'].map(id=>({id,...model.definition(id)}));
 manifest.push({name,channel:v+1,parameters:params.map((p,i)=>({...p,cc:20+i,exportId:name+'_'+p.rnbo}))});
 const patch=read('rnbo_'+name+'.maxpat').boxes.find(e=>e.box.id==='obj-rnbo').box.patcher;
 for(const entry of structuredClone(patch.boxes)){
  const b=entry.box,id=b.id;if(id==='rnbo-out2')continue;
  b.id=name+'-'+id;delete b.rnboinfo;
  if(b.rnbo_uniqueid)b.rnbo_uniqueid=name+'_'+b.rnbo_uniqueid;
  if(id==='rnbo-in'){b.text='inport hit_'+name;b.rnbo_classname='inport';delete b.rnbo_extra_attributes;}
  if(id==='rnbo-voice'){b.text='p '+name+'_core';b.patcher=read('rnbo_'+name+'_voice.rnbopat');}
  if(id==='rnbo-out1')b.text='out~ '+(v+1);
  if(b.text?.startsWith('param ')){
   const words=b.text.split(' ');words[1]=name+'_'+words[1];b.text=words.join(' ');b.varname=words[1];
  }
  if(b.patching_rect)b.patching_rect[0]+=v*700;
  boxes.push(entry);
 }
 for(const entry of structuredClone(patch.lines)){
  const l=entry.patchline;if(l.source[0]==='rnbo-out2'||l.destination[0]==='rnbo-out2')continue;
  l.source[0]=name+'-'+l.source[0];l.destination[0]=name+'-'+l.destination[0];lines.push(entry);
 }
}
const app=read('rnbo_kick.maxpat').appversion;
const rnbo={id:'engine',maxclass:'newobj',text:'rnbo~ @dumpoutlet 1',numinlets:1,numoutlets:10,outlettype:[...Array(8).fill('signal'),'list',''],patching_rect:[30,130,250,22],patcher:{fileversion:1,appversion:app,boxes,lines},saved_object_attributes:{uuid:'806fb0ac-cb97-491f-9b4d-f55a46dc2178',optimization:'O1'}};
const obj=(id,text,x,y)=>({box:{id,maxclass:'newobj',text,patching_rect:[x,y,350,22]}});
const wire=(a,b,o=0)=>({patchline:{source:[a,o],destination:[b,0]}});
fs.writeFileSync(path.join(dest,'rnbo_bank_export.maxpat'),JSON.stringify({patcher:{fileversion:1,appversion:app,rect:[100,100,760,260],boxes:[{box:rnbo},obj('script','v8 bank_export.js',30,80),obj('load','loadbang',410,80),{box:{id:'note',maxclass:'comment',text:'Eight-voice DPT export: silent harness, no MLR subscriptions or hardware flashing.',patching_rect:[30,25,700,22]}},{box:{id:'retry',maxclass:'message',text:'bang',patching_rect:[410,130,60,22]}}],lines:[wire('load','script'),wire('retry','script'),wire('script','engine'),wire('engine','script',9)]}},null,2)+'\n');
fs.writeFileSync(path.join(dest,'midi-map.json'),JSON.stringify(manifest,null,2)+'\n');
const f=n=>Number.isInteger(n)?n+'.0f':n+'f';
fs.writeFileSync(path.join(dest,'bank_parameters.h'),'// Generated by scripts/build_dpt_bank.js from desktop schemas.\n#pragma once\nnamespace Bank {\nstruct Parameter { const char* id; float lo,hi,initial; unsigned curve; };\nstatic const char* const names[8]={'+names.map(n=>JSON.stringify(n)).join(',')+'};\nstatic const Parameter parameters[8][12]={\n'+manifest.map(e=>'{'+e.parameters.map(p=>'{'+JSON.stringify(p.exportId)+','+[p.gridMin,p.gridMax,p.initial].map(f).join(',')+','+({linear:0,square:1,log:2}[p.scale]||0)+'}').join(',')+'}').join(',\n')+'\n};\n}\n');
